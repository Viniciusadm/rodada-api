CREATE TABLE matches (
  id CHAR(36) NOT NULL,
  organization_id CHAR(36) NOT NULL,
  game_id CHAR(36) NOT NULL,
  game_mode_id CHAR(36) NOT NULL,
  host_user_id CHAR(36) NOT NULL,
  name VARCHAR(180) NOT NULL,
  status VARCHAR(40) NOT NULL,
  current_round_id CHAR(36) NULL,
  winner_participant_id CHAR(36) NULL,
  started_at DATETIME(6) NULL,
  ended_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY matches_org_status_created_idx (organization_id, status, created_at),
  KEY matches_org_game_created_idx (organization_id, game_id, created_at),
  KEY matches_host_created_idx (host_user_id, created_at),
  KEY matches_game_mode_idx (game_mode_id),
  KEY matches_current_round_idx (current_round_id),
  KEY matches_winner_participant_idx (winner_participant_id),
  CONSTRAINT matches_org_fk FOREIGN KEY (organization_id) REFERENCES organizations (id),
  CONSTRAINT matches_game_fk FOREIGN KEY (game_id) REFERENCES games (id),
  CONSTRAINT matches_game_mode_fk FOREIGN KEY (game_mode_id) REFERENCES game_modes (id),
  CONSTRAINT matches_host_fk FOREIGN KEY (host_user_id) REFERENCES users (id),
  CONSTRAINT matches_status_check CHECK (status IN ('waiting', 'in_progress', 'finished', 'cancelled')),
  CONSTRAINT matches_time_order_check CHECK (ended_at IS NULL OR started_at IS NULL OR ended_at >= started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE match_settings (
  match_id CHAR(36) NOT NULL,
  max_rounds INT NULL,
  time_per_round_seconds INT NULL,
  initial_points INT NOT NULL DEFAULT 0,
  remote_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  capacity INT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (match_id),
  CONSTRAINT match_settings_match_fk FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
  CONSTRAINT match_settings_max_rounds_check CHECK (max_rounds IS NULL OR max_rounds > 0),
  CONSTRAINT match_settings_time_check CHECK (time_per_round_seconds IS NULL OR time_per_round_seconds > 0),
  CONSTRAINT match_settings_initial_points_check CHECK (initial_points >= 0),
  CONSTRAINT match_settings_capacity_check CHECK (capacity IS NULL OR capacity > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE match_questions (
  id CHAR(36) NOT NULL,
  match_id CHAR(36) NOT NULL,
  source_question_id CHAR(36) NULL,
  position INT NOT NULL,
  prompt_snapshot TEXT NOT NULL,
  expected_answer_snapshot TEXT NOT NULL,
  points INT NOT NULL,
  used_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY match_questions_match_position_unique (match_id, position),
  KEY match_questions_match_used_idx (match_id, used_at),
  KEY match_questions_source_question_idx (source_question_id),
  CONSTRAINT match_questions_match_fk FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
  CONSTRAINT match_questions_source_question_fk FOREIGN KEY (source_question_id) REFERENCES questions (id),
  CONSTRAINT match_questions_position_check CHECK (position > 0),
  CONSTRAINT match_questions_points_check CHECK (points >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE match_participants (
  id CHAR(36) NOT NULL,
  match_id CHAR(36) NOT NULL,
  player_id CHAR(36) NULL,
  display_name_snapshot VARCHAR(140) NOT NULL,
  normalized_name_snapshot VARCHAR(160) NOT NULL,
  join_source VARCHAR(40) NOT NULL,
  current_score INT NOT NULL DEFAULT 0,
  joined_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  left_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY match_participants_match_name_unique (match_id, normalized_name_snapshot),
  KEY match_participants_match_score_idx (match_id, current_score),
  KEY match_participants_player_idx (player_id),
  CONSTRAINT match_participants_match_fk FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
  CONSTRAINT match_participants_player_fk FOREIGN KEY (player_id) REFERENCES players (id),
  CONSTRAINT match_participants_join_source_check CHECK (join_source IN ('local', 'remote')),
  CONSTRAINT match_participants_time_order_check CHECK (left_at IS NULL OR left_at >= joined_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE match_rounds (
  id CHAR(36) NOT NULL,
  match_id CHAR(36) NOT NULL,
  match_question_id CHAR(36) NULL,
  round_number INT NOT NULL,
  status VARCHAR(40) NOT NULL,
  selected_participant_id CHAR(36) NULL,
  answer_revealed_at DATETIME(6) NULL,
  opened_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  closed_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY match_rounds_match_round_number_unique (match_id, round_number),
  KEY match_rounds_match_status_idx (match_id, status),
  KEY match_rounds_question_idx (match_question_id),
  KEY match_rounds_selected_participant_idx (selected_participant_id),
  CONSTRAINT match_rounds_match_fk FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
  CONSTRAINT match_rounds_question_fk FOREIGN KEY (match_question_id) REFERENCES match_questions (id),
  CONSTRAINT match_rounds_selected_participant_fk FOREIGN KEY (selected_participant_id) REFERENCES match_participants (id),
  CONSTRAINT match_rounds_status_check CHECK (status IN ('open', 'answer_revealed', 'closed')),
  CONSTRAINT match_rounds_round_number_check CHECK (round_number > 0),
  CONSTRAINT match_rounds_time_order_check CHECK (closed_at IS NULL OR closed_at >= opened_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE match_answers (
  id CHAR(36) NOT NULL,
  match_id CHAR(36) NOT NULL,
  match_round_id CHAR(36) NOT NULL,
  participant_id CHAR(36) NULL,
  result VARCHAR(40) NOT NULL,
  points_applied INT NOT NULL DEFAULT 0,
  answered_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY match_answers_round_participant_unique (match_round_id, participant_id),
  KEY match_answers_match_participant_idx (match_id, participant_id),
  CONSTRAINT match_answers_match_fk FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
  CONSTRAINT match_answers_round_fk FOREIGN KEY (match_round_id) REFERENCES match_rounds (id) ON DELETE CASCADE,
  CONSTRAINT match_answers_participant_fk FOREIGN KEY (participant_id) REFERENCES match_participants (id),
  CONSTRAINT match_answers_result_check CHECK (result IN ('correct', 'incorrect', 'skipped'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE score_events (
  id CHAR(36) NOT NULL,
  match_id CHAR(36) NOT NULL,
  participant_id CHAR(36) NOT NULL,
  match_round_id CHAR(36) NULL,
  actor_user_id CHAR(36) NULL,
  event_type VARCHAR(50) NOT NULL,
  delta INT NOT NULL,
  score_after INT NOT NULL,
  reason VARCHAR(255) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY score_events_match_created_idx (match_id, created_at),
  KEY score_events_participant_created_idx (participant_id, created_at),
  KEY score_events_round_idx (match_round_id),
  KEY score_events_actor_idx (actor_user_id),
  CONSTRAINT score_events_match_fk FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
  CONSTRAINT score_events_participant_fk FOREIGN KEY (participant_id) REFERENCES match_participants (id) ON DELETE CASCADE,
  CONSTRAINT score_events_round_fk FOREIGN KEY (match_round_id) REFERENCES match_rounds (id),
  CONSTRAINT score_events_actor_fk FOREIGN KEY (actor_user_id) REFERENCES users (id),
  CONSTRAINT score_events_type_check CHECK (event_type IN ('initial_points', 'correct_answer', 'incorrect_answer', 'manual_adjustment', 'penalty', 'reset'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
